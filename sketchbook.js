    /* Two chips, lying on the mat. They pan with the table — they go into
       #surface rather than onto #felt, so they do not float over a cloth that
       slides out from under them — and they drag the same way a played card
       does: press, move, drop, kept on the cloth. They are not in the model
       and they are not a game; they are just things on the table you can
       rearrange.

       Drawn rather than exported. A chip is four concentric circles and a dashed
       ring, which is less markup than an <img> would be request, and it takes
       the theme with it: the body is the brand accent and everything cut out of
       it is the mat's own colour, so the punched centres stay holes in the
       grass rather than a second green. */

    var CHIP_W = 52;

    function buildChip() {
        var wrap = document.createElement('div');
        wrap.className = 'chip';
        wrap.setAttribute('aria-hidden', 'true');
        wrap.style.setProperty('--chip-w', CHIP_W + 'px');

        var cast = document.createElement('div');
        cast.className = 'chip-cast';
        var disc = document.createElement('div');
        disc.className = 'chip-cast-disc';
        cast.appendChild(disc);
        wrap.appendChild(cast);

        var svg = document.createElementNS(SVG_NS, 'svg');
        svg.setAttribute('viewBox', '0 0 100 100');
        svg.style.pointerEvents = 'none';

        function circle(r, fill, stroke, width, dash, opacity) {
            var c = document.createElementNS(SVG_NS, 'circle');
            c.setAttribute('cx', '50');
            c.setAttribute('cy', '50');
            c.setAttribute('r', String(r));
            c.setAttribute('fill', fill || 'none');
            if (stroke) {
                c.setAttribute('stroke', stroke);
                c.setAttribute('stroke-width', String(width));
            }
            if (dash) c.setAttribute('stroke-dasharray', dash);
            if (opacity) c.setAttribute('opacity', String(opacity));
            svg.appendChild(c);
            return c;
        }

        circle(49, 'var(--accent)');
        // The two-tone edge, as a dashed stroke rather than six placed shapes:
        // one circumference divided six ways. At r=43 that is 270.2 units, so
        // each dash and its gap come to 45.03 — the numbers below are that
        // split, and they are why the rim closes exactly instead of leaving a
        // seam where the last dash meets the first.
        circle(43, null, 'var(--felt)', 12, '19 26.03');
        circle(33, null, 'var(--felt)', 2, null, 0.5);
        circle(17, 'var(--felt)', null, null, null, 0.92);
        wrap.appendChild(svg);
        return wrap;
    }

    // The opening you can actually see, above the hand, in surface coordinates.
    // Chips (and the dice that follow them) start on this band's rim so the
    // printed name in the middle of the cloth is left alone.
    function visibleOpening(pad) {
        var f = felt.getBoundingClientRect();
        var sr = surface.getBoundingClientRect();
        var viewX = f.left - sr.left, viewY = f.top - sr.top;
        var fanTop = fanEl.getBoundingClientRect().top - sr.top;
        return {
            x: viewX + pad,
            y: viewY + pad,
            w: Math.max(pad, f.width - pad * 2),
            h: Math.max(pad * 2, fanTop - viewY - pad - 24)
        };
    }

    // The printed name, in the surface's own pixels, plus a little air so a
    // chip's crescent cannot sit on a letter. Layout boxes, not screen rects:
    // the home card scales #felt and a bounding client rect would mix spaces.
    function titleKeepout() {
        var mark = document.getElementById('table-heading');
        var sw = tableW || surface.offsetWidth;
        var sh = tableH || surface.offsetHeight;
        var pad = 32;
        if (mark && mark.classList.contains('is-placed') && mark.offsetWidth > 0) {
            return {
                x: (parseFloat(mark.style.left) || 0) - pad,
                y: (parseFloat(mark.style.top) || 0) - pad,
                w: mark.offsetWidth + pad * 2,
                h: mark.offsetHeight + pad * 2
            };
        }
        var w = Math.min(560, sw * 0.62);
        var h = Math.min(200, sh * 0.28);
        return { x: sw / 2 - w / 2, y: sh / 2 - h / 2, w: w, h: h };
    }

    function overlapsKeep(x, y, size, keep) {
        return x < keep.x + keep.w && x + size > keep.x
            && y < keep.y + keep.h && y + size > keep.y;
    }

    function clampToBand(x, y, size, band) {
        return {
            x: Math.max(band.x, Math.min(x, band.x + band.w - size)),
            y: Math.max(band.y, Math.min(y, band.y + band.h - size))
        };
    }

    // If a draw (or a saved spot) sits on the name, slide it off along the
    // axis that clears the letters with the shortest move, then keep it in
    // the opening. Never returns a point on the keep-out if the band has room.
    function pushOffKeep(x, y, size, keep, band) {
        var spot = clampToBand(x, y, size, band);
        if (!overlapsKeep(spot.x, spot.y, size, keep)) return spot;
        var cx = spot.x + size / 2;
        var cy = spot.y + size / 2;
        var kcx = keep.x + keep.w / 2;
        var kcy = keep.y + keep.h / 2;
        var dx = cx - kcx;
        var dy = cy - kcy;
        var gap = 10;
        var alongX = Math.abs(dx) * keep.h >= Math.abs(dy) * keep.w;
        var tried = alongX
            ? { x: dx < 0 ? keep.x - size - gap : keep.x + keep.w + gap, y: spot.y }
            : { x: spot.x, y: dy < 0 ? keep.y - size - gap : keep.y + keep.h + gap };
        tried = clampToBand(tried.x, tried.y, size, band);
        if (!overlapsKeep(tried.x, tried.y, size, keep)) return tried;
        var other = alongX
            ? { x: spot.x, y: dy < 0 ? keep.y - size - gap : keep.y + keep.h + gap }
            : { x: dx < 0 ? keep.x - size - gap : keep.x + keep.w + gap, y: spot.y };
        return clampToBand(other.x, other.y, size, band);
    }

    // A seat beside the letters, in the opening. side is w / e / nw / ne / se.
    function wellNearTitle(band, keep, size, side) {
        var gap = 22;
        var kcx = keep.x + keep.w / 2;
        var kcy = keep.y + keep.h / 2;
        var x = kcx - size / 2;
        var y = kcy - size / 2;
        if (side === 'w') { x = keep.x - size - gap; y = kcy - size / 2; }
        else if (side === 'e') { x = keep.x + keep.w + gap; y = kcy - size / 2; }
        else if (side === 'nw') { x = keep.x - size * 0.2; y = keep.y - size - gap; }
        else if (side === 'ne') { x = keep.x + keep.w - size * 0.8; y = keep.y - size - gap; }
        else if (side === 'se') { x = keep.x + keep.w + gap; y = keep.y + keep.h + gap * 0.35; }
        else if (side === 'sw') { x = keep.x - size - gap; y = keep.y + keep.h + gap * 0.35; }
        return pushOffKeep(x, y, size, keep, band);
    }

    // A point beside the name, jittered, kept off the letters and off
    // whatever is already down. The fallback still pushes off the keep-out
    // — two chips on a short window still have to land, just not on the word.
    function rimSpot(band, keep, taken, size, side) {
        var seed = wellNearTitle(band, keep, size, side);
        var best = null, bestGap = -1;
        for (var t = 0; t < 48; t++) {
            var x = seed.x + (Math.random() - 0.5) * 52;
            var y = seed.y + (Math.random() - 0.5) * 40;
            var clamped = clampToBand(x, y, size, band);
            x = clamped.x;
            y = clamped.y;
            if (overlapsKeep(x, y, size, keep)) continue;
            var gap = Infinity;
            for (var i = 0; i < taken.length; i++) {
                var d = Math.abs(taken[i].x - x) + Math.abs(taken[i].y - y);
                if (d < gap) gap = d;
            }
            if (gap > bestGap) { bestGap = gap; best = { x: x, y: y }; }
            if (bestGap > size * 3) break;
        }
        if (best) return best;
        return pushOffKeep(seed.x, seed.y, size, keep, band);
    }

    // The rectangle a chip may sit in and stay whole, in the surface's own
    // coordinates. The whole surface, not the visible part: same reason a card
    // dragged off the edge of the window is still on the table.
    function chipBounds() {
        var s = surface.getBoundingClientRect();
        var pad = 8;
        return {
            minX: pad,
            maxX: Math.max(pad, s.width - CHIP_W - pad),
            minY: pad,
            maxY: Math.max(pad, s.height - CHIP_W - pad),
        };
    }

    function makeDraggableChip(el) {
        var drag = null;

        el.addEventListener('pointerdown', function (e) {
            if (e.button !== undefined && e.button !== 0) return;
            // The mat's pan handler is on #felt and would otherwise take this
            // press. Same stop a die uses, and for the same reason: the gesture
            // belongs to the thing under the pointer.
            e.stopPropagation();
            el.style.zIndex = String(++chipZ);
            drag = {
                id: e.pointerId,
                px: e.clientX, py: e.clientY,
                ox: parseFloat(el.style.left) || 0,
                oy: parseFloat(el.style.top) || 0,
                moved: false,
            };
            if (el.setPointerCapture) el.setPointerCapture(e.pointerId);
        });

        el.addEventListener('pointermove', function (e) {
            if (!drag || e.pointerId !== drag.id) return;
            var dx = e.clientX - drag.px, dy = e.clientY - drag.py;
            if (!drag.moved && Math.abs(dx) + Math.abs(dy) < DRAG_SLOP) return;
            if (!drag.moved) {
                drag.moved = true;
                drag.bounds = chipBounds();
                el.classList.add('is-dragging');
                el.style.willChange = 'transform';
            }
            var b = drag.bounds;
            var x = Math.min(Math.max(drag.ox + dx, b.minX), b.maxX);
            var y = Math.min(Math.max(drag.oy + dy, b.minY), b.maxY);
            el.style.left = Math.round(x) + 'px';
            el.style.top = Math.round(y) + 'px';
        });

        function end(e) {
            if (!drag || e.pointerId !== drag.id) return;
            if (el.releasePointerCapture && el.hasPointerCapture && el.hasPointerCapture(e.pointerId)) {
                el.releasePointerCapture(e.pointerId);
            }
            el.classList.remove('is-dragging');
            el.style.willChange = '';
            drag = null;
        }
        el.addEventListener('pointerup', end);
        el.addEventListener('pointercancel', end);
    }

    function scatterChips() {
        var taken = [];
        var band = visibleOpening(CHIP_W);
        var keep = titleKeepout();
        // Left of the name and right of it. The dice take north and south-east
        // of the same word, so the five pieces read as a ring, not a pile.
        var sides = ['w', 'e'];
        for (var i = 0; i < 2; i++) {
            var spot = rimSpot(band, keep, taken, CHIP_W, sides[i]);
            if (!spot) return;
            var chip = buildChip();
            chip.style.left = Math.round(spot.x) + 'px';
            chip.style.top = Math.round(spot.y) + 'px';
            // The print turns; the crescent does not. The sliver starts
            // down-right and dice.js nudges it a few pixels with the lamp.
            chip.style.setProperty('--chip-rot', Math.round(Math.random() * 360) + 'deg');
            // Ahead of #played. What puts a chip above a card is z-index, not
            // this order: see --die-z on #surface. Behind the grass canvas it
            // would be eaten: that canvas is opaque and the first child, so
            // this insert is what keeps a chip on the cloth.
            surface.insertBefore(chip, playedEl);
            makeDraggableChip(chip);
            taken.push(spot);
        }
    }

    /* ---------------- the card, opened ---------------- */

    /* A card's expand control puts it in a modal, larger, over a blurred page.
       The card in there is built fresh on every open and thrown away on close:
       there is then never a second copy of a work sitting in the document, and
       the rise always has a new element to play on. */

    var modalEl = document.getElementById('card-modal');
    var modalPanel = modalEl && modalEl.querySelector('[role="dialog"]');
    var modalCardEl = document.getElementById('modal-card');
    var modalOpener = null;

    function modalFocusable() {
        var all = modalEl.querySelectorAll('button, [href], input, select, textarea, iframe, [tabindex]:not([tabindex="-1"])');
        return Array.prototype.filter.call(all, function (el) {
            return !el.disabled && el.getClientRects().length > 0;
        });
    }

    function openModal(work, opener) {
        if (!modalEl || !modalCardEl || !work) return;
        modalOpener = opener || null;
        modalCardEl.innerHTML = '';

        // Front only, for now: no indices, no fold, no turn-over. The
        // details side lives on `modal-card-flip`. This card is the work
        // in a white frame, and it leans a little with the pointer.
        var card = buildCard(work, { embed: !!work.youtube });
        card.classList.add('is-expanded');

        // In here, and only in here, the card is cut to the shape of the work it
        // is showing: a landscape gif opens as a landscape card, a square one as
        // a square. It is written as --card-ar, the same custom property every
        // card's aspect-ratio already reads, overridden on this one element —
        // so the hand, the table and the rack are untouched and nothing has to
        // learn a second way of being a shape. The proportions come from the
        // work's own manifest entry rather than from a rule, which is the point:
        // a hundredth work added to works.json opens at its own size without
        // anything here changing. A side effect worth having is that the face's
        // object-fit: cover then has nothing left to crop.
        //
        // A YouTube work is 16:9 regardless of its poster. The live page plays
        // those as an embed, and a 5:7 well would letterbox the player into a
        // sliver. The box itself is also opened up on .is-embed, because the
        // 280px card the stills fit in is too small to watch.
        //
        // A work missing either number keeps the stylesheet's 5:7. The fit in
        // sketchbook.css divides by this ratio, and a card told to be 0 wide by
        // 0 high is a card with no size at all.
        if (work.youtube) {
            card.classList.add('is-embed');
            card.style.setProperty('--card-ar', '16 / 9');
        } else {
            var arW = Number(work.width), arH = Number(work.height);
            if (isFinite(arW) && isFinite(arH) && arW > 0 && arH > 0) {
                card.style.setProperty('--card-ar', arW + ' / ' + arH);
            }
        }

        modalCardEl.appendChild(card);
        wireModalTilt(card);

        // The dialog is named after the work it is showing, so it announces
        // something better than "dialog" when it takes focus.
        if (modalPanel) modalPanel.setAttribute('aria-label', work.title);
        modalEl.removeAttribute('hidden');
        // On <body>, which propagates to the viewport, so the scrollbar goes
        // with it and the scrim measures exactly the window.
        document.body.classList.add('modal-open');

        if (modalPanel) modalPanel.focus();
    }

    var modalTiltOff = null;

    // A few degrees toward the pointer, on the inner so it does not fight
    // the rise. Mouse and pen only: a finger has no cursor to follow.
    function wireModalTilt(card) {
        if (modalTiltOff) modalTiltOff();
        var reduce = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)');
        if (reduce && reduce.matches) return;

        function setTilt(x, y) {
            card.style.setProperty('--tilt-x', x.toFixed(2) + 'deg');
            card.style.setProperty('--tilt-y', y.toFixed(2) + 'deg');
        }

        function onMove(e) {
            if (e.pointerType && e.pointerType !== 'mouse' && e.pointerType !== 'pen') return;
            var r = card.getBoundingClientRect();
            if (!r.width || !r.height) return;
            var px = (e.clientX - r.left) / r.width - 0.5;
            var py = (e.clientY - r.top) / r.height - 0.5;
            px = Math.max(-0.65, Math.min(0.65, px));
            py = Math.max(-0.65, Math.min(0.65, py));
            setTilt(-py * 8, px * 10);
        }

        function onLeave() { setTilt(0, 0); }

        modalEl.addEventListener('pointermove', onMove);
        modalEl.addEventListener('pointerleave', onLeave);
        modalTiltOff = function () {
            modalEl.removeEventListener('pointermove', onMove);
            modalEl.removeEventListener('pointerleave', onLeave);
            modalTiltOff = null;
        };
    }

    function closeModal() {
        if (!modalEl || modalEl.hasAttribute('hidden')) return;
        if (modalTiltOff) modalTiltOff();
        modalEl.setAttribute('hidden', '');
        document.body.classList.remove('modal-open');
        modalCardEl.innerHTML = '';
        // Back to the control that opened it, or focus is left on nothing and
        // the next Tab starts from the top of the page.
        if (modalOpener && document.contains(modalOpener)) modalOpener.focus();
        modalOpener = null;
    }

    if (modalEl) {
        // Anywhere but the card closes it. Written as "not on the card" rather
        // than as a listener on the scrim: the panel is taller than the card it
        // holds, so a click in the space beside or below one would otherwise
        // land on the panel and do nothing, which reads as the page having
        // ignored you.
        modalEl.addEventListener('click', function (e) {
            if (!modalCardEl.contains(e.target)) closeModal();
        });

        document.addEventListener('keydown', function (e) {
            if (modalEl.hasAttribute('hidden')) return;
            if (e.key === 'Escape') { closeModal(); return; }
            if (e.key !== 'Tab') return;
            // Tab must not walk out of the modal and start operating the page
            // that is blurred behind it. Only the two ends are handled; in
            // between, the browser's own order is the right one.
            var f = modalFocusable();
            if (!f.length) { e.preventDefault(); return; }
            var i = f.indexOf(document.activeElement);
            var next = e.shiftKey ? i - 1 : i + 1;
            if (i === -1 || next < 0 || next >= f.length) {
                e.preventDefault();
                f[e.shiftKey ? f.length - 1 : 0].focus();
            }
        });
    }

    /* ---------------- the catalogue ---------------- */

    // The slots are made once and kept for the life of the page. Cards move
    // between them; the slots themselves never come or go, so the block holds
    // its footprint and the empties collect at the end rather than the whole
    // grid reflowing shorter every time a card is played.
    //
    // There is one slot per work still to come, which is the whole sketchbook
    // less the hand: a round opens by dealing HAND cards off the front of the
    // rack, and nothing ever puts a card back, so the rack peaks at
    // works.length - HAND on the first frame of a round and only falls from
    // there. Building works.length of them left the last five standing empty
    // for the life of the page, reading as five cards that had been played
    // before the page loaded.
    function buildGrid() {
        var frag = document.createDocumentFragment();
        slotEls = [];
        for (var i = 0; i < works.length - HAND; i++) {
            var slot = document.createElement('div');
            slot.className = 'slot';
            slotEls.push(slot);
            frag.appendChild(slot);
        }
        gridEl.appendChild(frag);
        deal(null);
    }

    // Opens a round: the rack is the whole pack, and the hand is taken off the
    // top of it before the rack is drawn - so the rack renders holding exactly
    // what is still to come, with the slots the hand is holding already standing
    // empty at the end. `from` deals the rack in from a point instead of simply
    // putting it there. `order`, when it is a full pack, is the order the table
    // just riffled into; without it the pack is shuffled fresh, which is how a
    // round opens.
    function deal(from, order) {
        while (fanEl.firstChild) fanEl.removeChild(fanEl.firstChild);
        hand = [];
        rack = (order && order.length === works.length) ? order.slice() : shuffle(works);
        var opening = rack.splice(0, HAND);
        fanEl.classList.add('is-placing');
        for (var i = 0; i < opening.length; i++) addToHand(opening[i], false);
        layOutFan();
        fillRack(from);
        // The rack just grew the page. A scrollbar can steal a few pixels
        // of felt, which would change the spread — lay it once more at the
        // width the reader actually has, still without easing.
        layOutFan();
        updateCount();
        void fanEl.offsetWidth;
        fanEl.classList.remove('is-placing');
    }

    /* ---------------- a rack tile that is being looked at ---------------- */

    /* A GIF cannot be paused. Once one is in the document it decodes and
       composites for as long as it is there, on screen or not, and nothing can
       stop it — so the only question is whether it is in the document, and this
       is the whole of the answer: the tile you are looking at holds its
       animation, and a tile well away from the window holds its poster again.

       There is no rootMargin, and that is the interesting part. The obvious
       thing to do here is to give the observer one so that a tile is already
       moving by the time it reaches the window, and the first version of this
       did: 300px, one tile row. It cost 37 MB on first paint. The rack's top
       row sits right at the fold on a 900px window, so a 300px margin reaches
       the row below it as well, and five animated tiles started downloading
       before the reader had scrolled a single pixel — most of the 47 MB this
       change exists to avoid, spent for nothing.

       So a tile plays when it is genuinely being looked at and not before. For
       the 17.7 MB work that means a wait while it arrives, and a margin would
       not have saved it: 300px of lead is about half a second of scrolling
       against a download measured in seconds. Better to spend nothing on the
       tiles nobody has looked at yet.

       Nothing here knows the rack's order. Tiles are moved between slots
       constantly, by a card being played and by the rack being dragged into a
       new order, and an IntersectionObserver follows the element rather than
       the place it sits in, so none of that has to know this exists. */
    var RACK_PLAY_AT = 0.4;      // of the tile on screen before it starts
    var rackWatch = null;

    /* Motion nobody asked for. The rest of this page answers the setting by
       cutting its transitions to nothing, and a GIF is the one thing on it that
       would ignore the setting completely: no controls, no way to pause it, and
       sixteen tiles of it going at once. So under reduce the rack keeps its
       posters and costs nothing at all. The hand and the table still play
       theirs, and that is not an inconsistency — those are cards you picked up
       and put down one at a time, which is a different thing from a wall of
       them starting on their own as you scroll past.

       Read when a tile is first watched rather than held in a variable, so
       changing the setting takes effect on the next deal instead of on a
       reload. */
    function motionWanted() {
        return !(window.matchMedia
            && window.matchMedia('(prefers-reduced-motion: reduce)').matches);
    }

    /* Puts the animation into the tile, but not until it has decoded. Assigning
       a src that has not arrived leaves the <img> empty until it does, and a
       tile that blanks as you scroll past it is worse than one that never
       moved; a decoded image paints on the very next frame instead. The poster
       and the GIF are the same 426x240, so nothing reflows either — though they
       are not the same picture, and the swap does land on whatever frame the
       animation is up to, which is what the animation starting looks like.

       The guard inside swap() is the other half of it. A fast flick carries a
       tile through the band and out again while the file is still on its way,
       and the point of all this is that such a tile does not end up holding
       it. */
    function playTile(img) {
        if (img.__live || img.__nomotion) return;
        img.__live = true;
        var pre = new Image();
        pre.decoding = 'async';
        pre.src = img.dataset.motion;
        var swap = function () {
            if (!img.__live || !img.parentNode) return;
            img.src = img.dataset.motion;
        };
        var give = function () {
            // The poster stays and this tile is never asked again: a file that
            // would not decode will not decode the second time either, and a
            // tile retrying it on every scroll is a worse fault than a still.
            img.__live = false;
            img.__nomotion = true;
        };
        if (pre.decode) pre.decode().then(swap, give);
        else { pre.onload = swap; pre.onerror = give; }
    }

    // And out again. The poster is in the cache by definition — it is what the
    // tile was showing a moment ago — so this is a repaint, not a load.
    function restTile(img) {
        if (!img.__live) return;
        img.__live = false;
        img.src = img.dataset.poster;
    }

    // The img rather than the card, because the img is the thing that holds the
    // file and the thing that survives the card being moved from slot to slot.
    function watchTile(card) {
        if (!window.IntersectionObserver || !motionWanted()) return;
        var img = card.querySelector('img[data-motion]');
        if (!img) return;
        if (!rackWatch) {
            // The ratio is read rather than isIntersecting, because the two
            // edges are deliberately not in the same place: a tile starts once
            // it is properly on screen and stops only once it has gone
            // completely. A tile parked halfway, which is where the rack's top
            // row sits when the page loads, then holds whatever it already had
            // instead of flicking between the two.
            rackWatch = new IntersectionObserver(function (entries) {
                for (var i = 0; i < entries.length; i++) {
                    var e = entries[i];
                    if (e.intersectionRatio >= RACK_PLAY_AT) playTile(e.target);
                    else if (!e.isIntersecting) restTile(e.target);
                }
            }, { threshold: [0, RACK_PLAY_AT] });
        }
        rackWatch.observe(img);
    }

    // Fills the rack from `rack`, one card per slot from the front. With `from`
    // - a point in client coordinates - every card starts there instead, face
    // down and the size it was on the table, and flies home turning over.
    function fillRack(from) {
        // A card being carried belongs to a rack that is about to stop
        // existing. It is pinned over #grid rather than sitting in a slot, so
        // emptying the slots below would leave it behind on the page.
        abandonCarry();
        // Every tile is about to be replaced, so the observer's list is stale
        // too. It holds its targets alive, and a rack rebuilt at the end of
        // every round would otherwise leave a round's worth of dead tiles in it
        // each time.
        if (rackWatch) rackWatch.disconnect();
        for (var i = 0; i < slotEls.length; i++) {
            while (slotEls[i].firstChild) slotEls[i].removeChild(slotEls[i].firstChild);
        }
        tileOf = {};
        var list = [];
        for (var i = 0; i < rack.length; i++) {
            var card = buildCard(rack[i], { still: true, back: true, lazy: true });
            slotEls[i].appendChild(card);
            tileOf[rack[i].id] = card;
            makeSortable(card, rack[i]);
            // A tile is a card you have not played yet, and wanting to read
            // about one before you decide to play it is the obvious thing to
            // want. Same control, same corner, same modal - it appears on
            // hover exactly as it does on the table, and its pointerdown is
            // stopped inside addExpand, so reaching for it never starts the
            // drag that would reorder the rack.
            addExpand(card);
            watchTile(card);
            list.push(card);
        }
        labelRack();
        if (!from) return;

        // Every rect read before any transform is written. One card's transform
        // cannot move another, but keeping the reads and the writes apart is
        // what stops a loop like this thrashing layout.
        var rects = list.map(function (c) { return c.getBoundingClientRect(); });
        list.forEach(function (c, i) {
            var r = rects[i];
            c.classList.add('is-flipped');
            c.style.transition = 'none';
            c.style.transform = 'translate('
                + (from.x - (r.left + r.width / 2)) + 'px,'
                + (from.y - (r.top + r.height / 2)) + 'px) scale('
                + (r.width ? playedW() / r.width : 0.5) + ')';
        });
        void gridEl.offsetWidth;
        list.forEach(function (c, i) {
            var at = i * DEAL_STEP_MS;
            setTimeout(function () {
                c.classList.add('is-moving');
                c.style.transition = '';
                c.style.transform = '';
            }, at);
            // The turn starts as the card lands, so the rack comes up face by
            // face rather than all at once at the end.
            setTimeout(function () { c.classList.remove('is-flipped'); }, at + 380);
            setTimeout(function () { c.classList.remove('is-moving'); }, at + 900);
        });
    }

    // Everything you can still do something with - the cards in your hand and
    // the cards still to come - out of what the sketchbook has. A card played
    // onto the table has left both, so the number only ever falls until the
    // round is reshuffled.
    function updateCount() {
        if (countEl) countEl.textContent = '(' + (hand.length + rack.length) + '/' + works.length + ')';
    }

    // Takes the work at `idx` out of the rack and hands it back, closing the
    // rack up behind it. This is the one way a card leaves the rack, whether it
    // is being drawn into your hand or the round is ending, so there is a
    // single place where `rack`, `tileOf` and the slots are kept in step.
    function takeFromRack(idx) {
        // A card in the air is put down before anything is spliced out from
        // under it. The rack can be dragged with one finger while the other
        // plays a card off the hand, and the splice below indexes `rack`
        // against the slots — which only agree once the carried card has landed.
        dropCarry(false);
        if (idx < 0 || idx >= rack.length) return null;
        var work = rack[idx];

        // First: where every card that is staying sits right now.
        var stay = [];
        for (var i = idx + 1; i < rack.length; i++) {
            var c = tileOf[rack[i].id];
            if (c) stay.push({ el: c, r: c.getBoundingClientRect() });
        }

        var leaving = tileOf[work.id];
        rack.splice(idx, 1);
        delete tileOf[work.id];

        // The one that has gone shrinks where it stood. It is lifted out of its
        // slot and pinned over the grid first, so the slot is already free for
        // the card advancing into it while this one is still on screen.
        if (leaving) {
            // It is about to shrink away and be taken off the page. Dropped
            // from the observer first, so nothing is left watching an element
            // that no longer exists.
            var gone = leaving.querySelector('img[data-motion]');
            if (gone && rackWatch) rackWatch.unobserve(gone);
            var lr = leaving.getBoundingClientRect();
            var gr = gridEl.getBoundingClientRect();
            gridEl.appendChild(leaving);
            leaving.style.left = (lr.left - gr.left) + 'px';
            leaving.style.top = (lr.top - gr.top) + 'px';
            leaving.style.width = lr.width + 'px';
            leaving.style.height = lr.height + 'px';
            void leaving.offsetWidth;
            leaving.classList.add('is-leaving');
            setTimeout(function () {
                if (leaving.parentNode) leaving.parentNode.removeChild(leaving);
            }, 360);
        }

        // Last: everything behind it moves up a slot.
        for (var i = idx; i < rack.length; i++) slotEls[i].appendChild(tileOf[rack[i].id]);

        // Invert, then play.
        for (var i = 0; i < stay.length; i++) {
            var now = stay[i].el.getBoundingClientRect();
            var dx = stay[i].r.left - now.left, dy = stay[i].r.top - now.top;
            if (!dx && !dy) continue;
            stay[i].el.classList.remove('is-moving');
            stay[i].el.style.transform = 'translate(' + dx + 'px,' + dy + 'px)';
        }
        void gridEl.offsetWidth;
        for (var i = 0; i < stay.length; i++) {
            stay[i].el.classList.add('is-moving');
            stay[i].el.style.transform = '';
        }

        updateCount();
        labelRack();
        return work;
    }

    /* ---------------- reordering the rack ---------------- */

    /* The upcoming cards are a running order, not a fixed list, so one can be
       picked up and dropped into another slot. The slots themselves still never
       move — only which card is in which — so this is takeFromRack()'s FLIP
       again, driven by a pointer instead of by a draw.

       The order is not decoration: the hand draws off the front of the rack, so
       dragging a card forward is how you choose what you get next. */

    // The card being carried, or null. Kept at this scope rather than inside
    // makeSortable() so that anything rebuilding the rack underneath a drag —
    // a play, a reshuffle — can put it down first.
    var carry = null;

    var rackStatus = document.getElementById('rack-status');

    function rackIndex(work) {
        for (var i = 0; i < rack.length; i++) if (rack[i].id === work.id) return i;
        return -1;
    }

    // `rack` with the card at `from` taken out and put back in at `to`. A
    // splice and not a swap: the cards in between shift by one, which is what
    // keeps the rack packed from the front rather than leaving a hole in the
    // middle with cards behind it.
    function orderWith(from, to) {
        var next = rack.slice();
        next.splice(to, 0, next.splice(from, 1)[0]);
        return next;
    }

    // Position is part of a tile's name. A reorder is otherwise invisible to a
    // reader who is not looking at the grid, and the keyboard path below is
    // nothing but a run of them.
    function labelRack() {
        for (var i = 0; i < rack.length; i++) {
            var c = tileOf[rack[i].id];
            if (!c) continue;
            c.setAttribute('aria-label',
                rack[i].title + ', ' + (i + 1) + ' of ' + rack.length + ' upcoming');
        }
    }

    function announce(msg) { if (rackStatus) rackStatus.textContent = msg; }

    // How many cards a row of the rack holds. Read off the grid rather than
    // written down: the column count steps from five to three to two on the way
    // to a phone, and this would be the fourth place that number lived.
    function columns() {
        var t = getComputedStyle(gridEl).gridTemplateColumns;
        return Math.max(1, t ? t.trim().split(/\s+/).length : 1);
    }

    // Puts `list` into the slots from the front and animates everything that
    // had to move. `held` is a work whose card is in the air: its slot is left
    // empty for it, and that gap is the preview of where the drop lands.
    function layOutRack(list, held) {
        var movers = [];
        // First: every rect read before a single card is touched.
        for (var i = 0; i < list.length; i++) {
            var c = tileOf[list[i].id];
            if (!c || (held && list[i].id === held.id)) continue;
            movers.push({ el: c, at: i, r: c.getBoundingClientRect() });
        }

        // Last. Every card comes out of its slot before any goes back in: a
        // card here can move either way along the rack, so appending into a
        // slot that has not been emptied yet leaves two cards stacked in it and
        // one slot showing the :empty hairline. takeFromRack() gets away without
        // the first pass because everything there only ever moves towards the
        // front, into a slot vacated a moment earlier.
        for (var i = 0; i < movers.length; i++) {
            if (movers[i].el.parentNode) movers[i].el.parentNode.removeChild(movers[i].el);
        }
        for (var i = 0; i < movers.length; i++) slotEls[movers[i].at].appendChild(movers[i].el);

        // Invert.
        for (var i = 0; i < movers.length; i++) {
            var now = movers[i].el.getBoundingClientRect();
            var dx = movers[i].r.left - now.left, dy = movers[i].r.top - now.top;
            if (!dx && !dy) continue;
            // The transition comes off first. A card caught mid-slide was
            // measured where it is on screen, and the offset has to be taken up
            // in one step rather than animated to.
            movers[i].el.classList.remove('is-moving');
            movers[i].el.style.transform = 'translate(' + dx + 'px,' + dy + 'px)';
        }
        void gridEl.offsetWidth;
        // Play.
        for (var i = 0; i < movers.length; i++) {
            movers[i].el.classList.add('is-moving');
            movers[i].el.style.transform = '';
        }
    }

    // One move, committed: the model, the slots and the labels in step.
    function moveCard(work, to) {
        var from = rackIndex(work);
        if (from === -1) return false;
        to = Math.min(Math.max(to, 0), rack.length - 1);
        if (to === from) return false;
        rack = orderWith(from, to);
        layOutRack(rack, null);
        labelRack();
        announce(work.title + ' moved to position ' + (to + 1) + ' of ' + rack.length);
        return true;
    }

    // Which slot the card in the air is over. The nearest slot centre rather
    // than whatever is under the pointer: the gutters between slots are dead
    // space, and a drop that did nothing because a finger was in one would read
    // as the page having missed the gesture.
    function slotUnder(cx, cy) {
        var best = 0, bestD = Infinity;
        for (var i = 0; i < carry.boxes.length; i++) {
            var dx = carry.boxes[i].cx - cx, dy = carry.boxes[i].cy - cy;
            var d = dx * dx + dy * dy;
            if (d < bestD) { bestD = d; best = i; }
        }
        return best;
    }

    // Puts the carried card down where the gap is. `animate` is false when
    // something else needs the rack this instant; either way the model and the
    // DOM come back into step before this returns.
    function dropCarry(animate) {
        if (!carry) return;
        var c = carry;
        carry = null;
        // A press that never cleared the slop never left its slot, so there is
        // nothing to put back.
        if (!c.lifted) {
            if (c.el.releasePointerCapture && c.el.hasPointerCapture && c.el.hasPointerCapture(c.id)) {
                c.el.releasePointerCapture(c.id);
            }
            return;
        }

        var was = c.el.getBoundingClientRect();
        rack = orderWith(c.from, c.to);
        c.el.classList.remove('is-lifted');
        c.el.style.left = '';
        c.el.style.top = '';
        c.el.style.width = '';
        c.el.style.height = '';
        c.el.style.transform = '';
        slotEls[c.to].appendChild(c.el);

        // Capture is released after the card is in its slot: doing it first
        // can fire pointercancel on this turn, and the handler would see a
        // carry that had already been dropped.
        if (c.el.releasePointerCapture && c.el.hasPointerCapture && c.el.hasPointerCapture(c.id)) {
            c.el.releasePointerCapture(c.id);
        }

        // The same FLIP the other cards get, so the card settles into the slot
        // from wherever it was let go of instead of snapping into it.
        if (animate) {
            var now = c.el.getBoundingClientRect();
            var dx = was.left - now.left, dy = was.top - now.top;
            if (dx || dy) {
                c.el.style.transform = 'translate(' + dx + 'px,' + dy + 'px)';
                void gridEl.offsetWidth;
                c.el.classList.add('is-moving');
                c.el.style.transform = '';
            }
        }
        labelRack();
        if (c.to !== c.from) {
            announce(c.work.title + ' moved to position ' + (c.to + 1) + ' of ' + rack.length);
        }
    }

    // A drag that left the grid is an abandoned move: the other tiles walk
    // back, and the card itself flies home to the slot it was picked up from.
    // Nearest-slot used to keep winning even off the rack, which is how a
    // card dragged onto the table or off the page could stall and sometimes
    // land in the wrong place.
    function returnCarry() {
        if (!carry) return;
        if (carry.lifted && carry.to !== carry.from) {
            carry.to = carry.from;
            layOutRack(rack, carry.work);
        } else {
            carry.to = carry.from;
        }
        dropCarry(true);
    }

    // The rack is being rebuilt from scratch, so there is no order left to
    // commit the carried card into — it is simply taken off the page.
    function abandonCarry() {
        if (!carry) return;
        var c = carry;
        carry = null;
        if (c.el.releasePointerCapture && c.el.hasPointerCapture && c.el.hasPointerCapture(c.id)) {
            c.el.releasePointerCapture(c.id);
        }
        if (c.el.parentNode === gridEl) gridEl.removeChild(c.el);
    }

    function makeSortable(el, work) {
        // A tile was a picture in a box; it is now something you can move, so
        // it has to be reachable without a pointer as well as with one.
        el.tabIndex = 0;
        el.setAttribute('aria-describedby', 'rack-help');

        // Belt to the images' braces, the same as a card on the table: pressing
        // on a picture and moving hands the gesture to the browser's own
        // drag-and-drop, and the pointer events simply stop arriving.
        el.addEventListener('dragstart', function (e) { e.preventDefault(); });

        el.addEventListener('pointerdown', function (e) {
            if (e.button !== undefined && e.button !== 0) return;
            // Not while the pack is coming together and going back out: every
            // card in the rack is about to be replaced.
            if (resetting || carry) return;
            if (rackIndex(work) === -1) return;
            carry = {
                el: el, work: work, id: e.pointerId,
                px: e.clientX, py: e.clientY,
                from: rackIndex(work), to: rackIndex(work),
                lifted: false, boxes: null, pin: null,
            };
            // Capture, so a drag that outruns the pointer keeps sending moves
            // here rather than to whichever tile is now underneath it.
            if (el.setPointerCapture) el.setPointerCapture(e.pointerId);
        });

        // Out of its slot and pinned over #grid, which is already positioned
        // for the card takeFromRack() flies out. Lifting frees the slot, so the card
        // shifting into it has somewhere to go while this one is still in hand.
        function lift() {
            carry.lifted = true;
            var r = el.getBoundingClientRect();
            var gr = gridEl.getBoundingClientRect();
            // Every slot measured once, here. Slots are fixed for the life of
            // the page and nothing in this gesture moves them, which keeps the
            // move handler off the layout entirely.
            carry.boxes = [];
            for (var i = 0; i < rack.length; i++) {
                var s = slotEls[i].getBoundingClientRect();
                carry.boxes.push({
                    cx: s.left - gr.left + s.width / 2,
                    cy: s.top - gr.top + s.height / 2,
                });
            }
            carry.pin = {
                cx: r.left - gr.left + r.width / 2,
                cy: r.top - gr.top + r.height / 2,
            };
            // Any transition still running would fight the pointer.
            el.classList.remove('is-moving');
            el.style.transform = '';
            gridEl.appendChild(el);
            el.classList.add('is-lifted');
            el.style.left = (r.left - gr.left) + 'px';
            el.style.top = (r.top - gr.top) + 'px';
            el.style.width = r.width + 'px';
            el.style.height = r.height + 'px';
        }

        el.addEventListener('pointermove', function (e) {
            if (!carry || carry.el !== el || e.pointerId !== carry.id) return;
            if (resetting) { abandonCarry(); return; }
            var dx = e.clientX - carry.px, dy = e.clientY - carry.py;
            // The same few pixels makePlayable() allows. A rack that threw a
            // tile out of its slot every time the page was touched would be
            // unusable on a phone, and unreadable with a mouse.
            if (!carry.lifted && Math.abs(dx) + Math.abs(dy) < DRAG_SLOP) return;
            if (!carry.lifted) lift();
            var area = gridEl.getBoundingClientRect();
            // Out of the rack: do not keep painting the card across the table
            // (or off the page), and do not drop it in the nearest slot as if
            // that were still a reorder. Send it home.
            if (e.clientX < area.left || e.clientX > area.right ||
                e.clientY < area.top || e.clientY > area.bottom) {
                returnCarry();
                return;
            }
            el.style.transform = 'translate(' + dx + 'px,' + dy + 'px)';

            var to = slotUnder(carry.pin.cx + dx, carry.pin.cy + dy);
            if (to === carry.to) return;
            carry.to = to;
            // The preview is the drop. What opens up under the card is exactly
            // where it lands if it is let go of here.
            layOutRack(orderWith(carry.from, to), carry.work);
        });

        function endDrag(e) {
            if (!carry || carry.el !== el || e.pointerId !== carry.id) return;
            var area = gridEl.getBoundingClientRect();
            if (carry.lifted &&
                (e.clientX < area.left || e.clientX > area.right ||
                 e.clientY < area.top || e.clientY > area.bottom)) {
                returnCarry();
                return;
            }
            dropCarry(true);
        }
        el.addEventListener('pointerup', endDrag);
        el.addEventListener('pointercancel', endDrag);

        // The same reorder without a pointer. Left and right step one slot; up
        // and down step a row, whatever a row is at this width.
        el.addEventListener('keydown', function (e) {
            if (resetting || carry) return;
            var step = 0;
            if (e.key === 'ArrowRight') step = 1;
            else if (e.key === 'ArrowLeft') step = -1;
            else if (e.key === 'ArrowDown') step = columns();
            else if (e.key === 'ArrowUp') step = -columns();
            else return;
            e.preventDefault();
            var from = rackIndex(work);
            if (from === -1) return;
            if (!moveCard(work, from + step)) return;
            // layOutRack() takes the tile out of the document to put it in its
            // new slot, and focus does not survive that — so it is put back,
            // and without the scroll that focus() would otherwise do on a page
            // whose scrolling is smooth site-wide.
            el.focus({ preventScroll: true });
        });
    }

    /* ---------------- the end of a round ---------------- */

    // Where the pack comes together: the middle of the part of the table you
    // can see, above the hand, in surface coordinates.
    function stackSpot() {
        var f = felt.getBoundingClientRect();
        var sr = surface.getBoundingClientRect();
        var top = f.top - sr.top;
        var fanTop = fanEl.getBoundingClientRect().top - sr.top;
        return {
            x: (f.left - sr.left) + (f.width - playedW()) / 2,
            y: top + Math.max(10, (fanTop - top - playedH()) / 2),
        };
    }

    // Every card in play comes together, the pack is riffled three times, and
    // the whole lot is dealt back into the rack face down, turning over one
    // by one. Each riffle splits the pack, interleaves the two halves, and
    // squares up in the new order — so the card that lands on top changes,
    // and the order the rack is dealt in is the order the table just mixed.
    function runReset() {
        if (resetting) return;
        resetting = true;

        var cards = Array.prototype.slice.call(playedEl.children);
        // One card's shadow is depth; twenty-one of them squared up on the
        // same spot is a dark smudge under the pack, because each card casts
        // over the one below instead of the table. The pile keeps its hairline
        // edge, which is what makes it read as paper at all.
        playedEl.classList.add('is-shuffling');
        var spot = stackSpot();
        var sr = surface.getBoundingClientRect();
        // Held in client coordinates for the deal, which happens after the
        // table has been cleared and there is nothing left to measure from.
        var from = { x: sr.left + spot.x + playedW() / 2, y: sr.top + spot.y + playedH() / 2 };

        cards.forEach(function (c, i) {
            c.classList.remove('is-dealing');
            c.classList.add('is-gathering');
            c.style.zIndex = String(SHUFFLE_Z + i);
            // A pack squares up, but not perfectly - a pixel or two of slop is
            // what makes it read as paper rather than as one thick card.
            place(c, spot.x + (i % 3) - 1, spot.y + (i % 2), 0);
        });

        var round = 0;
        var gap = playedW() * 0.55;

        // A real riffle, not a perfect zip: each hand drops one or two cards
        // at a time, and either half can start, so three of these do not put
        // the pack back where it began.
        function riffleOrder(pack) {
            var mid = Math.ceil(pack.length / 2);
            var a = pack.slice(0, mid);
            var b = pack.slice(mid);
            var ia = 0, ib = 0, out = [];
            var takeA = Math.random() < 0.5;
            while (ia < a.length || ib < b.length) {
                if (takeA && ia >= a.length) takeA = false;
                if (!takeA && ib >= b.length) takeA = true;
                var n = 1 + Math.floor(Math.random() * 2);
                if (takeA) {
                    while (n-- && ia < a.length) out.push(a[ia++]);
                } else {
                    while (n-- && ib < b.length) out.push(b[ib++]);
                }
                takeA = !takeA;
            }
            return out;
        }

        function stackPack(pack) {
            pack.forEach(function (c, i) {
                c.style.zIndex = String(SHUFFLE_Z + i);
                place(c, spot.x + (i % 3) - 1, spot.y + (i % 2), 0);
            });
        }

        function splitPack(pack) {
            var mid = Math.ceil(pack.length / 2);
            pack.forEach(function (c, i) {
                c.classList.remove('is-gathering');
                c.classList.add('is-riffling');
                var left = i < mid;
                c.style.zIndex = String(SHUFFLE_Z + i);
                place(c,
                    spot.x + (left ? -gap : gap) + (i % 2),
                    spot.y + (i % 3) - 1,
                    left ? -7 : 7);
            });
        }

        function riffle() {
            if (!cards.length || round >= 3) { redeal(); return; }
            splitPack(cards);
            setTimeout(function () {
                cards = riffleOrder(cards);
                stackPack(cards);
                round++;
                setTimeout(riffle, RIFFLE_MS);
            }, RIFFLE_MS);
        }

        function redeal() {
            playedEl.classList.remove('is-shuffling');
            var order = [];
            for (var i = cards.length - 1; i >= 0; i--) {
                if (cards[i].__work) order.push(cards[i].__work);
            }
            while (playedEl.firstChild) playedEl.removeChild(playedEl.firstChild);
            deal(from, order);
            resetting = false;
        }

        setTimeout(riffle, cards.length ? GATHER_MS : 0);
    }

    /* ---------------- the scene the home felt restores ---------------- */

    /* The home card contains this table live. What it needs when you leave
       is only where everything sat, so the same cloth opens onto the same
       pieces. There is no photograph. First visit has no list: chips and
       dice land on the rim the way they always have. */

    function readStore(key) {
        try {
            var raw = localStorage.getItem(key);
            if (!raw) return null;
            var o = JSON.parse(raw);
            return o && typeof o === 'object' ? o : null;
        } catch (err) {
            return null;
        }
    }

    function writeStore(key, value) {
        try { localStorage.setItem(key, JSON.stringify(value)); }
        catch (err) { /* private mode, or the picture was too large */ }
    }

    var savedScene = readStore(SCENE_KEY);
    if (savedScene && savedScene.v !== 1) savedScene = null;
    // dice.js reads this before it scatters, so a return visit puts the
    // dice back instead of rolling a new rim. Set even when there is
    // nothing to restore: that script also waits on __playgroundMatReady,
    // and a missing scene must not look like a scene that has not arrived.
    window.__playgroundScene = savedScene;

    function collectChips() {
        var out = [];
        var chips = surface.querySelectorAll(':scope > .chip');
        for (var i = 0; i < chips.length; i++) {
            out.push({
                x: parseFloat(chips[i].style.left) || 0,
                y: parseFloat(chips[i].style.top) || 0,
                rot: parseFloat(chips[i].style.getPropertyValue('--chip-rot')) || 0,
            });
        }
        return out;
    }

    function collectDice() {
        var out = [];
        var dice = surface.querySelectorAll(':scope > .die');
        for (var i = 0; i < dice.length; i++) {
            var d = dice[i];
            out.push({
                x: parseFloat(d.style.left) || 0,
                y: parseFloat(d.style.top) || 0,
                face: d.__value || parseInt(d.getAttribute('data-value'), 10) || 1,
                rz: (d.__angles && d.__angles.z) || 0,
            });
        }
        return out;
    }

    function collectCards() {
        var out = [];
        var kids = playedEl.children;
        for (var i = 0; i < kids.length; i++) {
            var el = kids[i];
            if (!el.classList || !el.classList.contains('card') || !el.dataset.id) continue;
            out.push({
                id: el.dataset.id,
                x: readVar(el, '--x'),
                y: readVar(el, '--y'),
                rot: readVar(el, '--rot'),
                flipped: el.classList.contains('is-flipped'),
                z: parseInt(el.style.zIndex, 10) || i + 1,
            });
        }
        return out;
    }

    function collectTitle() {
        var mark = document.getElementById('table-heading');
        if (!mark || !mark.classList.contains('is-placed')) return null;
        return {
            x: parseFloat(mark.style.left) || 0,
            y: parseFloat(mark.style.top) || 0,
        };
    }

    function collectScene() {
        return {
            v: 1,
            t: Date.now(),
            // No pan. Entering centres the cloth whatever is stored, so
            // keeping the old viewport would only be a value nothing reads.
            // Every position below is the surface's own, not the window's,
            // so none of them care where the table was scrolled to.
            title: collectTitle(),
            chips: collectChips(),
            dice: collectDice(),
            cards: collectCards(),
        };
    }

    function relativeBox(el, origin) {
        var r = el.getBoundingClientRect();
        return {
            x: r.left - origin.left,
            y: r.top - origin.top,
            w: r.width,
            h: r.height,
        };
    }

    function drawDyedText(ctx, el, origin, scale) {
        if (!el) return;
        var cs = getComputedStyle(el);
        var box = relativeBox(el, origin);
        var px = parseFloat(cs.fontSize) * scale;
        if (!(px > 0) || !el.textContent) return;
        ctx.save();
        ctx.font = cs.fontStyle + ' ' + cs.fontWeight + ' ' + px + 'px ' + cs.fontFamily;
        ctx.textAlign = 'center';
        ctx.textBaseline = 'middle';
        // The live title is the nap, clipped and multiplied with a grey.
        // Here the stand-in is a dark wash in the same letters: close
        // enough that the cross-fade does not flash a different word.
        ctx.fillStyle = 'rgba(36, 36, 36, 0.40)';
        ctx.fillText(
            el.textContent,
            (box.x + box.w / 2) * scale,
            (box.y + box.h / 2) * scale
        );
        ctx.restore();
    }

    function drawChipSnap(ctx, el, origin, scale) {
        var box = relativeBox(el, origin);
        var w = box.w;
        if (!(w > 2)) return;
        var accent = getComputedStyle(document.documentElement).getPropertyValue('--accent').trim() || '#5E81E2';
        var feltCol = getComputedStyle(document.documentElement).getPropertyValue('--felt').trim() || '#2a4528';
        var rot = (parseFloat(el.style.getPropertyValue('--chip-rot')) || 0) * Math.PI / 180;
        ctx.save();
        ctx.translate((box.x + w / 2) * scale, (box.y + box.h / 2) * scale);
        ctx.scale(scale, scale);
        ctx.fillStyle = 'rgba(0, 0, 0, 0.50)';
        ctx.beginPath();
        ctx.arc(w * 0.12, w * 0.16, w / 2, 0, Math.PI * 2);
        ctx.fill();
        ctx.rotate(rot);
        ctx.fillStyle = accent;
        ctx.beginPath();
        ctx.arc(0, 0, w / 2 - 0.8, 0, Math.PI * 2);
        ctx.fill();
        ctx.strokeStyle = feltCol;
        ctx.lineWidth = w * 0.12;
        ctx.setLineDash([w * 0.19, w * 0.2603]);
        ctx.beginPath();
        ctx.arc(0, 0, w * 0.43, 0, Math.PI * 2);
        ctx.stroke();
        ctx.setLineDash([]);
        ctx.globalAlpha = 0.92;
        ctx.fillStyle = feltCol;
        ctx.beginPath();
        ctx.arc(0, 0, w * 0.17, 0, Math.PI * 2);
        ctx.fill();
        ctx.restore();
    }

    var SNAP_PIPS = {
        1: [[1, 1]],
        2: [[0, 0], [2, 2]],
        3: [[0, 0], [1, 1], [2, 2]],
        4: [[0, 0], [2, 0], [0, 2], [2, 2]],
        5: [[0, 0], [2, 0], [1, 1], [0, 2], [2, 2]],
        6: [[0, 0], [2, 0], [0, 1], [2, 1], [0, 2], [2, 2]],
    };

    function drawDieSnap(ctx, el, origin, scale) {
        var box = relativeBox(el, origin);
        var w = box.w;
        if (!(w > 2)) return;
        var face = el.__value || parseInt(el.getAttribute('data-value'), 10) || 1;
        var rz = ((el.__angles && el.__angles.z) || 0) * Math.PI / 180;
        var stock = getComputedStyle(document.documentElement).getPropertyValue('--back-stock').trim() || '#F7F5F5';
        var ink = getComputedStyle(document.documentElement).getPropertyValue('--ink').trim() || '#111';
        ctx.save();
        ctx.translate((box.x + w / 2) * scale, (box.y + box.h / 2) * scale);
        ctx.scale(scale, scale);
        ctx.fillStyle = 'rgba(0, 0, 0, 0.48)';
        ctx.beginPath();
        ctx.roundRect(w * 0.18, w * 0.22, w, w, w * 0.12);
        ctx.fill();
        ctx.rotate(rz);
        ctx.fillStyle = stock;
        ctx.beginPath();
        ctx.roundRect(-w / 2, -w / 2, w, w, w * 0.12);
        ctx.fill();
        ctx.strokeStyle = 'rgba(0, 0, 0, 0.18)';
        ctx.lineWidth = 1;
        ctx.stroke();
        var pips = SNAP_PIPS[face] || SNAP_PIPS[1];
        var cell = w * 0.22;
        ctx.fillStyle = ink;
        for (var i = 0; i < pips.length; i++) {
            ctx.beginPath();
            ctx.arc((pips[i][0] - 1) * cell, (pips[i][1] - 1) * cell, w * 0.075, 0, Math.PI * 2);
            ctx.fill();
        }
        ctx.restore();
    }

    function drawCardSnap(ctx, el, origin, scale) {
        var box = relativeBox(el, origin);
        if (!(box.w > 4 && box.h > 4)) return;
        var img = el.querySelector('.card-face--front img');
        var flipped = el.classList.contains('is-flipped');
        var rot = (readVar(el, '--rot') || 0) * Math.PI / 180;
        ctx.save();
        ctx.translate((box.x + box.w / 2) * scale, (box.y + box.h / 2) * scale);
        ctx.rotate(rot);
        ctx.scale(scale, scale);
        var w = box.w, h = box.h, r = 8;
        ctx.beginPath();
        ctx.roundRect(-w / 2, -h / 2, w, h, r);
        ctx.fillStyle = getComputedStyle(document.documentElement).getPropertyValue('--stock').trim() || '#fff';
        ctx.fill();
        if (!flipped && img && img.naturalWidth) {
            ctx.save();
            ctx.clip();
            var inset = Math.max(2, w * 0.02);
            ctx.drawImage(img, -w / 2 + inset, -h / 2 + inset, w - inset * 2, h - inset * 2 - 18);
            ctx.restore();
        } else {
            ctx.fillStyle = getComputedStyle(document.documentElement).getPropertyValue('--back-stock').trim() || '#F7F5F5';
            ctx.fill();
        }
        ctx.strokeStyle = 'rgba(0, 0, 0, 0.12)';
        ctx.lineWidth = 1;
        ctx.stroke();
        ctx.restore();
    }


    function persistScene() {
        writeStore(SCENE_KEY, collectScene());
    }

    function surfaceBand(size) {
        var pad = 8;
        var sw = tableW || surface.offsetWidth;
        var sh = tableH || surface.offsetHeight;
        return {
            x: pad,
            y: pad,
            w: Math.max(pad, sw - pad * 2),
            h: Math.max(pad, sh - pad * 2)
        };
    }

    function placeSavedChips(list) {
        if (!list || !list.length) return false;
        var keep = titleKeepout();
        var band = surfaceBand(CHIP_W);
        for (var i = 0; i < list.length; i++) {
            var chip = buildChip();
            var parked = overlapsKeep(list[i].x, list[i].y, CHIP_W, keep)
                ? pushOffKeep(list[i].x, list[i].y, CHIP_W, keep, band)
                : { x: list[i].x, y: list[i].y };
            chip.style.left = Math.round(parked.x) + 'px';
            chip.style.top = Math.round(parked.y) + 'px';
            chip.style.setProperty('--chip-rot', Math.round(list[i].rot || 0) + 'deg');
            surface.insertBefore(chip, playedEl);
            makeDraggableChip(chip);
        }
        return true;
    }

    function seatPlayedEl(el, saved) {
        playedEl.appendChild(el);
        el.className = 'card';
        var z = saved.z || ++topZ;
        if (z > topZ) topZ = z;
        el.style.zIndex = String(z);
        if (el.flipBtn) {
            el.flipBtn.setAttribute('aria-label', el.dataset.title + ' — click to turn over, drag to move');
            el.flipBtn.setAttribute('aria-pressed', saved.flipped ? 'true' : 'false');
        }
        place(el, saved.x, saved.y, saved.rot);
        if (saved.flipped) el.classList.add('is-flipped');
        makePlayable(el);
        addExpand(el);
    }

    function restorePlayed(list) {
        if (!list || !list.length) return;
        var want = {};
        for (var i = 0; i < list.length; i++) want[list[i].id] = list[i];

        var fromRack = [];
        for (var r = rack.length - 1; r >= 0; r--) {
            var s = want[rack[r].id];
            if (!s) continue;
            var tile = tileOf[rack[r].id];
            if (tile && tile.parentNode) tile.parentNode.removeChild(tile);
            delete tileOf[rack[r].id];
            fromRack.push({ work: rack[r], saved: s });
            rack.splice(r, 1);
            delete want[s.id];
        }
        if (fromRack.length) fillRack(null);

        for (var h = hand.length - 1; h >= 0; h--) {
            var saved = want[hand[h].dataset.id];
            if (!saved) continue;
            var el = hand[h];
            el.removeEventListener('click', el.__play);
            el.__play = null;
            hand.splice(h, 1);
            seatPlayedEl(el, saved);
            delete want[saved.id];
        }

        for (var k = 0; k < fromRack.length; k++) {
            seatPlayedEl(buildCard(fromRack[k].work, { interactive: true }), fromRack[k].saved);
        }

        // Quiet refill: takeFromRack would shrink the tile it is taking,
        // and this is a restore, not a play. Pull the work off the rack
        // and rebuild the slots once at the end.
        var pulled = false;
        while (hand.length < HAND && rack.length) {
            var work = rack.shift();
            var tile = tileOf[work.id];
            if (tile && tile.parentNode) tile.parentNode.removeChild(tile);
            delete tileOf[work.id];
            addToHand(work, false);
            pulled = true;
        }
        if (pulled) fillRack(null);
        layOutFan();
        updateCount();
    }

    window.PlaygroundCover = { save: persistScene };

    /* ---------------- start ---------------- */

    sizeSurface();
    // Always the middle of the cloth, never where the table was left. The
    // name is dyed into the centre of the mat, so an arrival on a restored
    // pan is an arrival on a table whose title is off to one side or
    // scrolled away entirely — and the first thing a visitor should see is
    // what the page is called. Where the pieces lie is saved; which part of
    // the cloth you are looking at is not worth keeping at that price.
    centrePan();
    placeMatMark();
    if (document.fonts && document.fonts.ready) {
        document.fonts.ready.then(function () { placeMatMark(); }).catch(function () {});
    }

    worksPromise
        .then(function (data) {
            works = (data && data.works) || [];
            if (!works.length) throw new Error('works.json held no works');
            // Before anything is built: every face wants to know which card it
            // is, and that is a property of the manifest's order, not of the
            // shuffle that is about to happen to it.
            assignCards();
            // buildGrid deals the opening round: the rack, and the hand off
            // the top of it.
            buildGrid();
            sizeSurface();
            // Again, because the grid has just changed how big the cloth is
            // and the middle has moved with it.
            centrePan();
            placeMatMark();
            // After the pan, which is what decides which part of the table is
            // the visible part a chip has to land in. A saved rim is put
            // back; a first visit scatters the way it always has.
            if (!savedScene || !placeSavedChips(savedScene.chips)) scatterChips();
            if (savedScene) restorePlayed(savedScene.cards);
            window.__playgroundMatReady = true;
            requestAnimationFrame(function () {
                requestAnimationFrame(persistScene);
            });
        })
        .catch(function (err) {
            // The catalogue is the page; without it there is nothing to show,
            // and an empty grid with a heading counting to zero would read as a
            // sketchbook with nothing in it rather than as a page that failed.
            if (emptyEl) emptyEl.hidden = false;
            if (countEl) countEl.textContent = '';
            console.error('[sketchbook]', err);
            window.__playgroundMatReady = true;
        });

    function onLeave() { persistScene(); }
    window.addEventListener('pagehide', onLeave);
    document.addEventListener('visibilitychange', function () {
        if (document.visibilityState === 'hidden') persistScene();
    });

    // The fan is placed in pixels off its own measured width, so a resize that
    // crosses the breakpoint has to re-lay it out.
    var resizeTimer = null;
    window.addEventListener('resize', function () {
        clearTimeout(resizeTimer);
        resizeTimer = setTimeout(function () {
            layOutFan();
            // The cloth may need to grow with the window; it will not shrink.
            // applyPan then keeps the current view inside the new limits.
            sizeSurface();
            applyPan();
            placeMatMark();
        }, 120);
    });
